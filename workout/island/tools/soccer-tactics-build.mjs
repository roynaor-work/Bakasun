import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {createHash} from 'node:crypto';

/** Strip authoring prose while retaining every runtime ID, anchor and numeric
 * example. This keeps the deterministic simulation synchronous in Node and on
 * older mobile module engines, without duplicating a hand-tuned formation. */
export function soccerTacticsRuntimeData(source){
 const docs=new Set(['coordinateContract','roleLegend','provenance','label','description','trigger','action','recommendedRange','cpuCost','unit','cpuCostMeaning']);
 const copy=value=>Array.isArray(value)?value.map(copy):value&&typeof value==='object'?Object.fromEntries(Object.entries(value).filter(([key,child])=>!docs.has(key)&&(key!=='example'||typeof child==='number')).map(([key,child])=>[key,copy(child)])):value;
 return copy(source);
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===path.resolve(process.argv[1])){
 const raw=await readFile(new URL('../design/tactics/soccer.json',import.meta.url),'utf8'),data=soccerTacticsRuntimeData(JSON.parse(raw));
 const text='// Generated by tools/soccer-tactics-build.mjs from the checked-in soccer design.\n'+
  'export const SOCCER_TACTICS_SOURCE_SHA256='+JSON.stringify(createHash('sha256').update(raw).digest('hex'))+';\n'+
  'export const SOCCER_TACTICS_DATA='+JSON.stringify(data)+';\n';
 await writeFile(new URL('../minigames/soccer-tactics-data.mjs',import.meta.url),text);
 console.log(JSON.stringify({bytes:Buffer.byteLength(text),source:'design/tactics/soccer.json'}));
}
