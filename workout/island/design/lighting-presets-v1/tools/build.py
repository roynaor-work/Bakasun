#!/usr/bin/env python3
"""Rebuild original PNGs, the file-safe data snapshot and the offline ZIP.

Python 3 + Pillow; no downloads. presets.json is the editable source of truth.
Run from any directory. Only files inside this package are written.
"""
from pathlib import Path
import base64
import hashlib
import json
import math
import zipfile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE = 'lighting-presets-v1.zip'
RUNTIME = [
    'preview.html', 'preview.css', 'preview.js', 'lighting.js', 'preset-data.js',
    'presets.json', 'LICENSES.md', 'REPORT.md', 'vendor/three.local.js',
    'vendor/LICENSE.three', 'textures/sky-tile.png', 'textures/clouds.png',
    'textures/halo.png', 'tools/serve.py',
]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def textures():
    target = ROOT / 'textures'
    target.mkdir(exist_ok=True)
    # Finite Fourier basis: matching opposite edges in BOTH axes, no seams.
    sky = Image.new('RGB', (256, 256))
    waves = [(1, 2, .0, .27), (3, -1, .7, .14), (2, 5, 1.1, .08),
             (7, 3, 2.6, .045), (11, -5, .4, .025)]
    for y in range(256):
        for x in range(256):
            u, v = x / 255, y / 255
            value = .5 + sum(a * math.cos(2 * math.pi * (i*u+j*v)+p)
                             for i, j, p, a in waves)
            shade = round(255 * min(1, max(0, value)))
            sky.putpixel((x, y), (shade, shade, shade))
    sky.save(target / 'sky-tile.png', optimize=True)
    # White RGB + smooth straight alpha. Neutral assets can be tinted by a preset.
    cloud = Image.new('RGBA', (256, 128), (255, 255, 255, 0))
    lobes = [(.27, .57, .16, .19, .85), (.41, .40, .15, .28, .95),
             (.56, .48, .18, .27, .94), (.72, .58, .16, .19, .82),
             (.47, .67, .29, .13, .80)]
    for y in range(128):
        for x in range(256):
            u, v = x/255, y/127
            density = sum(a * math.exp(-3 * (((u-cx)/rx)**2+((v-cy)/ry)**2))
                          for cx, cy, rx, ry, a in lobes)
            edge = math.sin(math.pi*u)**2 * math.sin(math.pi*v)**2
            alpha = round(255 * min(.98, density) * min(1, edge*7))
            cloud.putpixel((x, y), (255, 255, 255, alpha))
    cloud.save(target / 'clouds.png', optimize=True)
    halo = Image.new('RGBA', (128, 128), (255, 255, 255, 0))
    for y in range(128):
        for x in range(128):
            radius = math.hypot((x-63.5)/63.5, (y-63.5)/63.5)
            alpha = (math.exp(-radius*radius*7) * (1-radius)**2
                     if radius < 1 else 0)
            halo.putpixel((x, y), (255, 255, 255, round(alpha*255)))
    halo.save(target / 'halo.png', optimize=True)


def embed():
    path = ROOT / 'presets.json'
    pack = json.loads(path.read_text())
    inline = {}
    for asset in pack['assets'].values():
        data = (ROOT / asset['path']).read_bytes()
        asset['bytes'] = len(data)
        asset['sha256'] = digest(data)
        inline[asset['path']] = 'data:image/png;base64,' + base64.b64encode(data).decode()
    path.write_text(json.dumps(pack, ensure_ascii=False, indent=2) + '\n')
    snapshot = ('/* Generated by tools/build.py from presets.json and textures/. */\n'
                'globalThis.LIGHTING_PACK = ' + json.dumps(pack, ensure_ascii=False, separators=(',', ':')) + ';\n'
                'globalThis.LIGHTING_TEXTURES = ' + json.dumps(inline, separators=(',', ':')) + ';\n')
    (ROOT / 'preset-data.js').write_text(snapshot)


def archive():
    # Stable timestamps/order; the archive never includes itself or screenshots.
    with zipfile.ZipFile(ROOT / ARCHIVE, 'w', compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9) as output:
        for name in RUNTIME:
            path = ROOT / name
            if not path.is_file():
                raise FileNotFoundError(path)
            info = zipfile.ZipInfo('lighting-presets-v1/' + name, (2026, 11, 17, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            output.writestr(info, path.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    files = [{ 'path': n, 'bytes': (ROOT/n).stat().st_size,
               'sha256': digest((ROOT/n).read_bytes()) } for n in RUNTIME]
    result = dict(version=1, budgetBytes=3_000_000,
                  runtimeBytes=sum(f['bytes'] for f in files),
                  textureBytes=sum(f['bytes'] for f in files if f['path'].startswith('textures/')),
                  archiveBytes=(ROOT/ARCHIVE).stat().st_size,
                  archiveSHA256=digest((ROOT/ARCHIVE).read_bytes()), files=files)
    (ROOT / 'manifest.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({k:v for k,v in result.items() if k!='files'}, indent=2))


if __name__ == '__main__':
    textures()
    embed()
    archive()
