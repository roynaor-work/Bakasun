#!/usr/bin/env python3
"""Behavior checks against the delivered GLB preview. Requires Playwright + Chromium."""
import argparse,json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://127.0.0.1:8765/workout/island/design/alpine-runner-v1/preview.html')
parser.add_argument('--chromium',default='/usr/bin/chromium')
args=parser.parse_args()
checks=[]; errors=[];requests=[]
def check(name,condition,evidence=None):
    checks.append({'name':name,'pass':bool(condition),'evidence':evidence})
    if not condition: print('FAIL:',name,evidence)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=args.chromium,headless=True,args=['--no-sandbox','--use-gl=angle','--use-angle=swiftshader'])
    page=browser.new_page(viewport={'width':844,'height':390},device_scale_factor=1)
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
    page.on('requestfailed',lambda r:requests.append({'url':r.url,'failure':r.failure}))
    page.goto(args.url+'?test=1')
    page.wait_for_function('window.__alpine?.snapshot().ready || window.__alpineError',timeout=60000)
    api=lambda js:page.evaluate('window.__alpine.'+js)
    snap=lambda:api('snapshot()')
    def reset(): api('restart();window.__alpine.clear()')
    check('all assets loaded',snap()['ready'],page.evaluate('window.__alpineError'))
    check('844x390 canvas',page.locator('#world').bounding_box()['width']==844)
    page.screenshot(path=str(ROOT/'verification/preview-844x390.webp'),type='webp',quality=88)
    page.locator('#start').click();api('clear()')
    page.keyboard.press('ArrowLeft');api('advance(.4)')
    check('keyboard left changes lane',snap()['lane']==-1)
    page.keyboard.press('ArrowLeft');check('lane left clamps',snap()['lane']==-1)
    page.keyboard.press('ArrowRight');page.keyboard.press('ArrowRight');api('advance(.4)')
    check('keyboard right reaches right lane',snap()['lane']==1)
    page.keyboard.press('ArrowRight');check('lane right clamps',snap()['lane']==1)
    reset();page.mouse.move(450,180);page.mouse.down();page.mouse.move(370,180);page.mouse.up();api('advance(.4)')
    check('pointer swipe changes lane',snap()['lane']==-1)
    reset();api("inject('coin',0,5);window.__alpine.advance(.4)")
    check('coin collects in lane',snap()['coins']==1,snap()['coins'])
    reset();api("inject('low_fence',0,7);window.__alpine.command('jump');window.__alpine.advance(.5)")
    check('jump clears physical 1.03m fence',snap()['collisions']==0 and snap()['rootHeight']>1.05,{'height':snap()['rootHeight'],'collisions':snap()['collisions']})
    page.screenshot(path=str(ROOT/'verification/jump-844x390.webp'),type='webp',quality=85)
    api('advance(.65)');check('jump returns to glide',snap()['action']=='glide' and abs(snap()['rootHeight'])<.01,snap()['action'])
    reset();api("inject('high_beam',0,5.6);window.__alpine.command('slide');window.__alpine.advance(.5)")
    check('slide clears beam during low hold',snap()['collisions']==0 and snap()['action']=='slide')
    page.screenshot(path=str(ROOT/'verification/slide-844x390.webp'),type='webp',quality=85)
    reset();api("inject('high_beam',0,5.6);window.__alpine.advance(.5)")
    check('standing skier hits beam',snap()['collisions']==1)
    api('advance(2.5)');check('fall recovers to glide',snap()['action']=='glide' and not snap()['falling'],snap()['action'])
    for kind in ['low_fence','tree','rock','cable_car','ice_crevasse','snowman','penguin','rolling_snowball']:
        reset();api(f"inject('{kind}',0,5);window.__alpine.advance(.5)")
        check('collision '+kind,snap()['collisions']==1)
    reset();api("inject('star',0,5);window.__alpine.advance(.4)");check('star collects',snap()['stars']==1)
    reset();api("inject('magnet',0,5);window.__alpine.advance(.4);window.__alpine.inject('coin',-1,7);window.__alpine.advance(.1)");check('magnet collects adjacent lane',snap()['coins']==1 and 'magnet' in snap()['powers'])
    reset();api("inject('shield',0,5);window.__alpine.advance(.4);window.__alpine.inject('rock',0,5);window.__alpine.advance(.4)")
    check('shield absorbs collision and is consumed',snap()['collisions']==0 and 'shield' not in snap()['powers'])
    reset();api("inject('magnet',0,5);window.__alpine.advance(.4);window.__alpine.inject('coin',-1,8);window.__alpine.advance(.1)")
    check('magnet attracts another lane',snap()['coins']==1 and 'magnet' in snap()['powers'])
    reset();api("inject('double_coin',0,5);window.__alpine.advance(.4);window.__alpine.inject('coin',0,5);window.__alpine.advance(.4)")
    check('double coin awards two',snap()['coins']==2)
    reset();api("inject('turbo',0,5);window.__alpine.advance(.4)");before=snap()['distance'];api('advance(1)')
    check('turbo accelerates and animates',snap()['distance']-before>21 and snap()['action']=='turbo')
    api('advance(6)');check('turbo expires',not snap()['powers'].get('turbo') and snap()['action']=='glide')
    reset();api("command('jump');window.__alpine.advance(.1);window.__alpine.suit(1);window.__alpine.advance(.1)")
    check('suit change safely resets transient action',snap()['suit']==1 and snap()['action']=='glide' and not snap()['falling'])
    api("command('pause')");paused=snap();api('advance(4)')
    check('pause freezes distance and action',snap()['distance']==paused['distance'] and snap()['actionTime']==paused['actionTime'])
    page.locator('#pause').click();check('pause button resumes',snap()['running'])
    reset();api('advance(150)');long=snap()
    check('stream visits all eight variants',len(long['visited'])==8,long['visited'])
    check('stream keeps six tile slots',long['tileCount']==6,long['tileCount'])
    check('entity population remains bounded',long['entityCount']<130,long['entityCount'])
    reset();api('advance(1)')
    page.screenshot(path=str(ROOT/'verification/running-844x390.webp'),type='webp',quality=88)
    for name in ['gentle_turn','slope','bridge','ice_tunnel','village','forest','summit']:
        api(f"inspectTile('{name}');window.__alpine.advance(.2)")
        page.screenshot(path=str(ROOT/f'verification/tile-{name}.webp'),type='webp',quality=80)
    reset();api("inject('shield',0,5);window.__alpine.advance(.4);window.__alpine.restart()")
    check('restart resets scores powers and distance',snap()['coins']==0 and snap()['stars']==0 and snap()['distance']==0 and not snap()['powers'])
    check('no browser errors',not errors,errors)
    check('no failed requests',not requests,requests)
    report={'schemaVersion':1,'browser':browser.version,'viewport':{'width':844,'height':390},'mode':'Chromium software WebGL; deterministic 120Hz advance; no physical phone performance claim','checks':checks,'passed':sum(c['pass'] for c in checks),'failed':sum(not c['pass'] for c in checks),'errors':errors,'requestFailures':requests,'longRun':long}
    (ROOT/'verification/browser.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({'passed':report['passed'],'failed':report['failed'],'errors':errors},ensure_ascii=False))
    browser.close()
if any(not c['pass'] for c in checks):raise SystemExit(1)
