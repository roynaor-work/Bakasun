def analyze(spec, source_stats):
    name, title, duration, loop, gain, kind, seed = spec
    entry = {"id": name, "name": title, "duration_seconds": duration, "loop": loop,
             "recommended_volume": gain, "event": kind, "seed": seed,
             "source_lufs": source_stats["lufs"], "files": {}}
    checks = []
    loop_versions = {}
    for ext in ("ogg", "mp3"):
        path = ROOT / f"{name}.{ext}"
        probe = json.loads(run(["ffprobe", "-v", "error", "-show_streams", "-show_format",
                               "-of", "json", str(path)]).stdout)
        stream = probe["streams"][0]
        assert len(probe["streams"]) == 1 and stream["codec_type"] == "audio"
        x = decode(path)
        stats = meter(x)
        decoded_duration = len(x) / SR
        size = path.stat().st_size
        errors = []
        if not 0 < size <= MAX_BYTES:
            errors.append("file_size")
        if abs(decoded_duration - duration) > 1 / SR:
            errors.append("decoded_duration")
        if abs(stats["lufs"] - TARGET_LUFS) > LOUDNESS_TOLERANCE:
            errors.append("loudness")
        if stats["true_peak_dbtp"] > -2:
            errors.append("true_peak")
        if not np.isfinite(x).all() or np.max(np.abs(x)) >= 1:
            errors.append("clipping_or_nonfinite")
        if abs(np.mean(x)) > .001:
            errors.append("dc_offset")
        if int(stream["sample_rate"]) != SR or stream["channels"] != 1:
            errors.append("audio_format")
        endpoints = max(abs(float(x[0])), abs(float(x[-1])))
        if not loop and endpoints > .002:
            errors.append("one_shot_endpoints")
        result = {"file": path.name, "bytes": size,
                  "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                  "codec": stream["codec_name"], "sample_rate_hz": int(stream["sample_rate"]),
                  "channels": stream["channels"], "decoded_samples": len(x),
                  "decoded_duration_seconds": decoded_duration,
                  "container_duration_seconds": float(probe["format"]["duration"]),
                  "lufs": stats["lufs"], "true_peak_dbtp": stats["true_peak_dbtp"],
                  "sample_peak_dbfs": round(db(np.max(np.abs(x))), 3),
                  "dc_offset": round(float(np.mean(x)), 8),
                  "endpoint_abs_max": round(endpoints, 8)}
        if loop:
            result["seam"] = seam_metrics(x)
            loop_versions[ext.upper()] = x
            if not result["seam"]["pass"]:
                errors.append("loop_seam")
        checks.append({**result, "pass": not errors, "errors": errors})
        entry["files"][ext] = {k: result[k] for k in ("file", "bytes", "sha256", "lufs", "true_peak_dbtp")}
    return entry, checks, loop_versions


