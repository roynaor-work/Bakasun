def clock(duration):
    return np.arange(round(duration * SR), dtype=np.float64) / SR


def rms(x):
    return float(np.sqrt(np.mean(np.square(x))))


def db(x):
    return 20 * math.log10(max(float(x), 1e-12))


def noise(rng, n, low=100, high=7000):
    sos = signal.butter(3, [low, high], btype="bandpass", fs=SR, output="sos")
    return signal.sosfilt(sos, rng.standard_normal(n))


def envelope(t, attack=.012, release=.08):
    return np.sin(np.minimum(t / attack, 1) * np.pi / 2) ** 2 * np.sin(
        np.minimum(np.maximum(t[-1] - t, 0) / release, 1) * np.pi / 2
    ) ** 2


def place(out, part, at):
    start = round(at * SR)
    if start < 0 or start >= len(out):
        raise ValueError("Invalid event start")
    size = min(len(part), len(out) - start)
    out[start:start + size] += part[:size]


def room(x, wet=.16, circular=False):
    """Small original tapped room response; no recorded impulse response."""
    out = x.copy()
    for delay, gain in ((.031, .46), (.057, .33), (.089, .25), (.137, .18),
                        (.193, .12), (.271, .07)):
        k = round(delay * SR)
        if circular:
            out += wet * gain * np.roll(x, k)
        else:
            out[k:] += wet * gain * x[:-k]
    return out


def whistle(rng, duration, events):
    out = np.zeros(round(duration * SR))
    for at, length, pitch in events:
        t = clock(length)
        # Two air-column modes, detuned pea flutter and filtered breath.
        f = pitch * (1 + .005 * np.sin(2 * np.pi * 31 * t)
                     + .002 * np.sin(2 * np.pi * 73 * t))
        f *= 1 + .025 * np.exp(-t * 75) - .018 * (t / length) ** 5
        phase = 2 * np.pi * np.cumsum(f) / SR
        air = noise(rng, len(t), 1800, 8500)
        tone = np.sin(phase) + .54 * np.sin(1.067 * phase + .2)
        tone += .12 * np.sin(2 * phase)
        flutter = .85 + .15 * np.sin(2 * np.pi * 42 * t + .4)
        place(out, (tone * flutter + .10 * air) * envelope(t, .009, .035), at)
    return room(out, .20)


def voice(rng, duration, pitch, formants, excited=False):
    """Additive glottal excitation weighted by vowel formants; no speech model."""
    t = clock(duration)
    contour = (1 + (.20 if excited else .07) * np.sin(np.pi * t / duration))
    contour -= (.06 if excited else .16) * t / duration
    f = pitch * contour * (1 + .008 * np.sin(2 * np.pi * rng.uniform(4, 7) * t))
    phase = 2 * np.pi * np.cumsum(f) / SR + rng.uniform(0, 2 * np.pi)
    out = np.zeros(len(t))
    for harmonic in range(1, min(50, int(7500 / (pitch * 1.3)))):
        hz = harmonic * f
        weight = np.zeros(len(t))
        for center, width, gain in formants:
            weight += gain * np.exp(-.5 * ((hz - center) / width) ** 2)
        out += weight / harmonic ** .65 * np.sin(harmonic * phase)
    out += .045 * noise(rng, len(t), 400, 5500)
    out *= .85 + .15 * np.sin(2 * np.pi * rng.uniform(6, 11) * t + rng.uniform(0, 6))
    return out * envelope(t, .08, .23)


def crowd(rng, duration, cheer):
    out = np.zeros(round(duration * SR))
    vowels = ([(650, 150, 1), (1150, 220, .9), (2700, 350, .35)] if cheer else
              [(360, 100, 1), (760, 150, .9), (2350, 300, .16)])
    for _ in range(26 if cheer else 23):
        length = rng.uniform(.6, 1.6) if cheer else rng.uniform(1.0, 1.65)
        at = rng.uniform(.025, .55 if cheer else .27)
        shifted = [(f * rng.uniform(.87, 1.15), w, g) for f, w, g in vowels]
        v = voice(rng, length, rng.uniform(105, 280), shifted, cheer)
        place(out, v * rng.uniform(.4, 1), at)
    if cheer:
        for _ in range(37):
            t = clock(.12)
            clap = noise(rng, len(t), 800, 8500) * np.exp(-t * 65)
            clap *= envelope(t, .001, .02)
            place(out, .25 * clap, rng.uniform(.2, duration - .25))
    return room(out, .60)


def ambience(rng):
    """Periodic spectral noise + low, indistinct, circular formant murmurs."""
    t = clock(8)
    freq = np.fft.rfftfreq(len(t), 1 / SR)
    spectral = 1 / np.maximum(freq, 85) ** .53
    spectral *= (1 - np.exp(-(freq / 110) ** 4)) * np.exp(-(freq / 3200) ** 4)
    spectrum = (rng.standard_normal(len(freq)) + 1j * rng.standard_normal(len(freq)))
    spectrum *= spectral
    spectrum[0] = spectrum[-1] = 0
    out = np.fft.irfft(spectrum, n=len(t))
    out /= rms(out)
    out *= .86 + .05 * np.sin(2 * np.pi * 2 * t / 8) + .025 * np.sin(2 * np.pi * 5 * t / 8)
    # An anonymous, low murmur, distributed around the circle with wraparound.
    murmurs = np.zeros(len(t))
    for _ in range(45):
        v = voice(rng, rng.uniform(.45, 1.25), rng.uniform(95, 205),
                  [(330, 140, 1), (870, 200, .45), (1800, 300, .12)])
        at = rng.integers(0, len(t))
        indices = (at + np.arange(len(v))) % len(t)
        murmurs[indices] += v * rng.uniform(.4, .9)
    out += .13 * murmurs / rms(murmurs)
    out = room(out, .45, circular=True)
    # Select a naturally quiet seam with a small slope; no silent fade/dip.
    step = np.abs(out - np.roll(out, 1))
    scores = np.abs(out) + .6 * step
    boundary = int(np.argmin(scores))
    return np.roll(out, -boundary)


def bounce(rng, duration, strength):
    t = clock(duration - .015)
    # Air cavity, rubber shell and inharmonic hardwood resonances.
    pitch = (108, 119, 132)[strength]
    phase = 2 * np.pi * (pitch * t + (13 + 9 * strength) * .024 * (1 - np.exp(-t / .024)))
    hit = np.sin(phase) * np.exp(-t * (18 - 2 * strength))
    hit += .40 * np.sin(1.76 * phase + .4) * np.exp(-t * 32)
    for hz, gain, decay in ((345, .25, 38), (690, .11, 48), (1310, .06, 65)):
        hit += gain * np.sin(2 * np.pi * hz * t) * np.exp(-t * decay)
    hit += (.12 + .15 * strength) * noise(rng, len(t), 700, 7500) * np.exp(-t * 135)
    hit *= envelope(t, .0014, .05)
    out = np.zeros(round(duration * SR))
    place(out, hit, .015)
    return room(out, .19 + .03 * strength)


def swish(rng, duration):
    t = clock(duration - .02)
    friction = noise(rng, len(t), 850, 9000)
    sweep = (t / .045) * np.exp(1 - t / .045)
    out = friction * sweep * (.70 + .30 * np.sin(2 * np.pi * (29 * t + 40 * t * t)))
    for at, amp in ((.045, .45), (.079, .32), (.116, .22), (.158, .13)):
        k = round(at * SR)
        out[k:] += amp * friction[:-k] * np.exp(-clock((len(t) - k) / SR) * 28)
    out *= envelope(t, .006, .08)
    result = np.zeros(round(duration * SR))
    place(result, out, .02)
    return room(result, .12)


def squeak(rng, duration, variant):
    out = np.zeros(round(duration * SR))
    gestures = ([(.02, .29, 1500, 600)], [(.02, .46, 2150, -1050)],
                [(.02, .20, 1350, 650), (.27, .23, 2050, -600)])[variant]
    for at, length, base, sweep in gestures:
        t = clock(length)
        f = base + sweep * t / length + 110 * np.sin(2 * np.pi * 17 * t)
        f += 35 * np.sin(2 * np.pi * 73 * t)
        phase = 2 * np.pi * np.cumsum(f) / SR
        stick_slip = .55 + .45 * np.sin(2 * np.pi * (37 * t + 18 * t * t)) ** 2
        tone = np.sin(phase) + .24 * np.sin(2 * phase) + .08 * np.sin(3 * phase)
        tone = tone * stick_slip + .24 * noise(rng, len(t), 650, 7500)
        place(out, tone * envelope(t, .012, .065), at)
    return room(out, .23)


def synthesize(spec):
    name, _, duration, loop, _, kind, seed = spec
    rng = np.random.Generator(np.random.PCG64(seed))
    if kind == "steal":
        out = whistle(rng, duration, [(.015, .19, 2920)])
    elif kind == "foul":
        out = whistle(rng, duration, [(.015, 1.06, 2800)])
    elif kind == "quarter_start":
        out = whistle(rng, duration, [(.015, .18, 2870), (.30, .28, 2870)])
    elif kind == "quarter_end":
        out = whistle(rng, duration, [(.015, .16, 2820), (.27, .16, 2820), (.53, .83, 2820)])
    elif kind == "ambience":
        out = ambience(rng)
    elif kind in ("miss", "basket"):
        out = crowd(rng, duration, kind == "basket")
    elif kind == "swish":
        out = swish(rng, duration)
    elif kind.startswith("bounce_"):
        out = bounce(rng, duration, ["bounce_soft", "bounce_medium", "bounce_hard"].index(kind))
    elif kind.startswith("squeak_"):
        out = squeak(rng, duration, int(kind[-1]) - 1)
    else:
        raise ValueError(name)
    out -= np.mean(out)
    if not loop:
        out *= envelope(clock(duration), .004, .04)
    assert np.isfinite(out).all() and len(out) == round(duration * SR)
    return out


def meter(x):
    args = ["ffmpeg", "-hide_banner", "-nostdin", "-f", "f32le", "-ar", str(SR),
            "-ac", "1", "-i", "pipe:0", "-af",
            f"loudnorm=I={TARGET_LUFS}:TP=-2:LRA=7:print_format=json", "-f", "null", "-"]
    raw = run(args, np.asarray(x, dtype="<f4").tobytes()).stderr.decode()
    stats = json.loads(re.findall(r"\{[^{}]+\}", raw)[-1])
    return {"lufs": float(stats["input_i"]), "true_peak_dbtp": float(stats["input_tp"])}


def normalize(x):
    x = x / max(np.max(np.abs(x)), 1e-12) * .7
    for _ in range(3):
        stats = meter(x)
        if not math.isfinite(stats["lufs"]):
            raise ValueError("Unmeasurable loudness")
        x *= 10 ** ((TARGET_LUFS - stats["lufs"]) / 20)
        if np.max(np.abs(x)) > .76:
            # Control exceptional transient crest before remeasuring loudness.
            x = .76 * np.tanh(x / .76)
    stats = meter(x)
    assert abs(stats["lufs"] - TARGET_LUFS) <= .15, stats
    assert stats["true_peak_dbtp"] <= -2, stats
    return x, stats


def encode(x, path, seed):
    args = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
            "-fflags", "+bitexact", "-f", "f32le", "-ar", str(SR), "-ac", "1",
            "-i", "pipe:0", "-map_metadata", "-1", "-flags:a", "+bitexact",
            "-fflags", "+bitexact"]
    if path.suffix == ".ogg":
        # Short pages avoid ambiguous first-page granules on subsecond Vorbis.
        args += ["-c:a", "libvorbis", "-q:a", "2", "-serial_offset", str(seed),
                 "-page_duration", "100000"]
    else:
        args += ["-c:a", "libmp3lame", "-b:a", "48k", "-write_xing", "1",
                 "-id3v2_version", "0", "-write_id3v1", "0"]
    run(args + [str(path)], np.asarray(x, dtype="<f4").tobytes())


def calibrated_encode(x, path, seed):
    # Codec quantization and the MP3 synthesis gain change perceived loudness.
    # Calibrate the actual decoded deliverable rather than just the input PCM.
    gain_db = 0.0
    for _ in range(5):
        encode(x * 10 ** (gain_db / 20), path, seed)
        stats = meter(decode(path))
        error = TARGET_LUFS - stats["lufs"]
        if abs(error) <= .10:
            return
        gain_db += error
    raise RuntimeError(f"Codec loudness calibration did not converge: {path.name}")


def decode(path):
    # Preserve the decoder's native duration: never hide encoder padding by trimming.
    proc = run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-i", str(path),
                "-f", "f32le", "-acodec", "pcm_f32le", "-ac", "1", "-ar", str(SR), "-"])
    return np.frombuffer(proc.stdout, dtype="<f4").astype(np.float64)


def seam_metrics(x):
    n = round(.05 * SR)
    joined = np.r_[x[-n:], x[:n]]
    seam = abs(float(x[0] - x[-1]))
    step_rms = rms(np.diff(x))
    # Compare the whole transition neighborhood with typical loop energy.
    local = rms(joined)
    ratio = local / rms(x)
    slope_error = abs(float((x[1] - x[0]) - (x[-1] - x[-2])))
    jump_limit = max(.003, 4 * step_rms)
    slope_limit = max(.006, 6 * step_rms)
    passed = seam <= jump_limit and slope_error <= slope_limit and .65 <= ratio <= 1.45
    return {"boundary_jump": round(seam, 8), "jump_limit": round(jump_limit, 8),
            "slope_error": round(slope_error, 8), "slope_limit": round(slope_limit, 8),
            "seam_rms_over_global_rms": round(ratio, 5),
            "step_rms": round(step_rms, 8), "pass": bool(passed)}


