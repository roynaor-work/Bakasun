def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify-only", action="store_true", help="verify without rewriting any package files")
    args = parser.parse_args()
    for tool in ("ffmpeg", "ffprobe"):
        if not shutil.which(tool):
            parser.error(f"Missing required tool: {tool}")
    manifest = {"schema_version": 1, "pack": "hoops-referee-audio-v1", "license": "CC0-1.0",
                "sample_rate_hz": SR, "channels": 1, "normalization_lufs": TARGET_LUFS,
                "max_true_peak_dbtp": -2, "max_file_bytes": MAX_BYTES,
                "volume_unit": "linear amplitude multiplier after normalization",
                "loop_start_seconds": 0, "loop_end_seconds": 8, "sounds": []}
    verification = {"base_commit": BASE_COMMIT, "target_lufs": TARGET_LUFS,
                    "loudness_tolerance_lu": LOUDNESS_TOLERANCE,
                    "max_file_bytes": MAX_BYTES,
                    "tools": {"ffmpeg": run(["ffmpeg", "-version"]).stdout.decode().splitlines()[0],
                              "numpy": np.__version__}, "files": []}
    import scipy
    verification["tools"]["scipy"] = scipy.__version__
    loop_versions = {}
    for spec in SPECS:
        source, source_stats = normalize(synthesize(spec))
        if not args.verify_only:
            for ext in ("ogg", "mp3"):
                calibrated_encode(source, ROOT / f"{spec[0]}.{ext}", spec[-1])
        entry, checks, decoded_loop = analyze(spec, source_stats)
        manifest["sounds"].append(entry)
        verification["files"].extend(checks)
        if spec[3]:
            verification["source_loop_seam"] = seam_metrics(source)
            loop_versions = {"PCM source": source, **decoded_loop}
        print(f'{spec[0]}: ' + ", ".join(f'{c["codec"]} {c["bytes"]} B {c["lufs"]:.2f} LUFS '
                                            f'{"PASS" if c["pass"] else c["errors"]}' for c in checks), flush=True)
    verification["pass"] = all(f["pass"] for f in verification["files"]) and verification["source_loop_seam"]["pass"]
    if not verification["pass"]:
        raise SystemExit("Audio verification failed; see the per-file console results")
    if args.verify_only:
        shipped = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
        if shipped != manifest:
            raise SystemExit("Manifest does not match decoded files / synthesis settings")
    else:
        (ROOT / "manifest.json").write_text(json_text(manifest), encoding="utf-8")
        graph_loop(loop_versions, ROOT / "loop-check.png")
        verification["loop_graph"] = "loop-check.png"
        (ROOT / "verification.json").write_text(json_text(verification), encoding="utf-8")
        write_report(manifest, verification)
        html = re.sub(r'(?<=<!-- MANIFEST_START -->).*?(?=<!-- MANIFEST_END -->)',
                      lambda _: '\n<script id="manifest" type="application/json">' +
                      json_text(manifest) + '</script>\n', LISTEN_TEMPLATE, flags=re.S)
        (ROOT / "listen.html").write_text(html, encoding="utf-8")
        (ROOT / "LICENSE.txt").write_text(LICENSE_TEXT, encoding="utf-8")
    package_files = [p for p in ROOT.rglob("*") if p.is_file()]
    oversize = [(p.relative_to(ROOT).as_posix(), p.stat().st_size) for p in package_files if p.stat().st_size > MAX_BYTES]
    if oversize:
        raise SystemExit(f"Package files exceed {MAX_BYTES} B: {oversize}")
    print(f"PASS: {len(SPECS)} sounds / 28 audio files; all {len(package_files)} package files <= {MAX_BYTES} B")


if __name__ == "__main__":
    main()
