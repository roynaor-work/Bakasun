import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CATS } from '../../../js/exercises.js';
import { MAX_BYTES, SPEED, VIEWBOX, frameFor, renderExercise, samplesFor, selectExercises } from './motion.mjs';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
async function output(path, content) {
  const url = new URL(path, root);
  if (check) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Stale generated file: ${fileURLToPath(url)}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
const exercises = [];
const artwork = {};
for (const { exercise, count } of selectExercises()) {
  const svg = renderExercise(exercise);
  artwork[exercise.id] = svg.replace(/^<\?xml[^>]+>\s*/, '').trim();
  const bytes = Buffer.byteLength(svg);
  if (bytes > MAX_BYTES) throw new Error(`${exercise.id}: ${bytes} bytes exceeds ${MAX_BYTES}`);
  const { duration, segments } = samplesFor(exercise);
  const poster = renderExercise(exercise, { animated: false });
  await output(`animations/${exercise.id}.svg`, svg);
  await output(`posters/${exercise.id}.svg`, poster);
  exercises.push({
    id: exercise.id, name: exercise.name, category: exercise.cat, categoryName: CATS[exercise.cat].name,
    programCount: count, src: `animations/${exercise.id}.svg`, poster: `posters/${exercise.id}.svg`,
    bytes, posterBytes: Buffer.byteLength(poster), durationMs: Math.round(duration), segments,
    sourceCycleMs: Math.round(duration * SPEED), view: ['jumping-jacks', 'side-hops', 'jump-rope'].includes(exercise.id) ? 'front' : 'side',
    viewBox: frameFor(exercise),
  });
}
const manifest = {
  version: 1, title: 'האימון שלי — ספריית תנועה דו־ממדית',
  source: 'workout/js/exercises.js', rankingSource: 'workout/js/programs.js',
  selection: 'Program presence, excluding warm-up and stretch blocks; catalog order breaks ties. Not measured user popularity.',
  format: 'SVG with native SMIL; no JavaScript, fonts, embedded bitmaps, or external requests.',
  speed: SPEED, maxBytes: MAX_BYTES, viewBox: VIEWBOX, exercises,
};
await output('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
await output('catalog.js', `// Generated by tools/build.mjs. Inline artwork keeps the gallery functional on file://, without a server.\nwindow.ROYIKI_CATALOG = ${JSON.stringify(manifest)};\nwindow.ROYIKI_ARTWORK = ${JSON.stringify(artwork)};\n`);
console.table(exercises.map(e => ({ exercise: e.id, programs: e.programCount, KB: (e.bytes / 1000).toFixed(1), seconds: (e.durationMs / 1000).toFixed(2) })));
console.log(`${check ? 'Checked' : 'Built'} 12 self-contained loops; largest ${Math.max(...exercises.map(e => e.bytes))} / ${MAX_BYTES} bytes.`);
