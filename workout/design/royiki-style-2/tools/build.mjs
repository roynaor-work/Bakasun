import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CATS, EXERCISES } from '../../../js/exercises.js';
import { MAX_BYTES, SPEED, frameFor, previous, renderExercise, samplesFor, selectExercises, viewFor } from './motion.mjs';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
async function output(path, content) {
  const url = new URL(path, root);
  if (check) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`Stale generated file: ${fileURLToPath(url)}`);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}
const exercises = [], artwork = {};
for (const { exercise, batch } of selectExercises()) {
  const svg = renderExercise(exercise), poster = renderExercise(exercise, { animated: false });
  artwork[exercise.id] = svg.replace(/^<\?xml[^>]+>\s*/, '').trim();
  const bytes = Buffer.byteLength(svg);
  if (bytes > MAX_BYTES) throw new Error(`${exercise.id}: ${bytes} bytes exceeds ${MAX_BYTES}`);
  const { duration, segments } = samplesFor(exercise);
  await output(`animations/${exercise.id}.svg`, svg);
  await output(`posters/${exercise.id}.svg`, poster);
  exercises.push({
    id: exercise.id, name: exercise.name, category: exercise.cat, categoryName: CATS[exercise.cat].name,
    batch, src: `animations/${exercise.id}.svg`, poster: `posters/${exercise.id}.svg`, bytes,
    posterBytes: Buffer.byteLength(poster), durationMs: duration, sourceCycleMs: Math.round(duration * SPEED),
    segments, view: viewFor(exercise), prop: exercise.prop ?? null, viewBox: frameFor(exercise),
  });
}
const manifest = {
  version: 1, title: 'האימון שלי — 38 ההדגמות הנוספות', source: 'workout/js/exercises.js',
  reference: 'workout/design/royiki-style/manifest.json', referencePr: 244,
  selection: 'Catalog order, excluding the 12 IDs in the PR 244 manifest. Two batches of 19.',
  format: 'Self-contained SVG with native SMIL; static SVG posters; no scripts, fonts, bitmaps or external requests.',
  speed: SPEED, maxBytes: MAX_BYTES, catalogCount: EXERCISES.length,
  previousCount: previous.exercises.length, exercises,
};
await output('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
await output('catalog.js', `// Generated by tools/build.mjs; inline artwork supports offline/file:// viewing.\nwindow.ROYIKI_CATALOG = ${JSON.stringify(manifest)};\nwindow.ROYIKI_ARTWORK = ${JSON.stringify(artwork)};\n`);
const rows = exercises.map(e => `| \`${e.id}\` | ${e.name} | ${e.batch} | [${e.src}](${e.src}) | ${(e.bytes / 1000).toFixed(2)} |`);
await output('mapping.md', '# מזהה תרגיל ← קובץ SVG\n\n38 התרגילים שלא נכללו ב־PR 244, בסדר הקטלוג; שתי מנות של 19. גדלים לפני דחיסה, KB = 1,000 בתים.\n\n| מזהה בקטלוג | שם | מנה | קובץ | KB |\n|---|---|---:|---|---:|\n' + rows.join('\n') + '\n');
console.table(exercises.map(e => ({ exercise: e.id, batch: e.batch, KB: (e.bytes / 1000).toFixed(1), seconds: (e.durationMs / 1000).toFixed(2) })));
console.log(`${check ? 'Checked' : 'Built'} ${exercises.length} loops; largest ${Math.max(...exercises.map(e => e.bytes))} / ${MAX_BYTES} bytes.`);
