// אורך משפט סטטי לפי band
const band = line => line[2] || null;

export function ageBand(profile = {}) {
  const age = Number(profile.age);
  return age > 0 && age <= 7 ? 'y' : 'b';
}
export function voiceCopyEnabled(profile = {}, search = '') {
  if (/[?&]voiceV1=0\b/.test(search)) return false;
  return profile.voiceV1 !== false;
}
export function dayPart(hour) { return hour >= 5 && hour < 11 ? 'morning' : hour >= 17 || hour < 4 ? 'evening' : 'day'; }

export function createVoiceCopy({ rng = Math.random } = {}) {
  const last = new Map();
  // בוחר ניסוח מרשימת המועמדים; לא חוזר על האחרון שנבחר באותו מצב, כל עוד יש מה לבחור
  const choose = (key, items) => {
    const prev = last.get(key);
    const pool = items.length > 1 ? items.filter((_, i) => i !== prev) : items;
    const pick = pool[Math.floor(rng() * pool.length) % pool.length];
    last.set(key, items.indexOf(pick));
    return pick;
  };
  // pick('cheer', ctx) -> { text, tts }
  const pick = (key, ctx = {}) => {
    const b = ctx.band || 'b';
    const items = COPY[key].filter(l => !band(l) || band(l) === b);
    const line = choose(key, items);
    return { text: line[0], tts: line[1] };
  };
  const nameOpen = (ctx, text, tts) => ctx.name ? { text: `${ctx.name}, ${text}`, tts: `${ctx.name}, ${tts}` } : { text, tts };
  // השאלה אחרי אימון: לפעמים עם שם הילד
  const howWas = ctx => {
    if (ctx.name && rng() < .3) return nameOpen(ctx, 'סיימת! איך היה? קל, בדיוק או קשה?', 'סִיַּמְתָּ! אֵיךְ הָיָה? קַל, בְּדִיּוּק אוֹ קָשֶׁה?');
    return pick('howWas', ctx);
  };
  const week = (st, ctx) => {
    const n = st.thisWeek, ord = SAY_UI.ordinals[n], ordTts = SAY_UI_TTS.ordinals[n];
    const forms = [
      { text: `זה האימון ${ord || `מספר ${n}`} שלך השבוע. כל הכבוד!`, tts: `זֶה הָאִמּוּן ${ordTts || `מִסְפָּר ${n}`} שֶׁלְּךָ הַשָּׁבוּעַ. כָּל הַכָּבוֹד!` },
      { text: `האימון ${ord || `מספר ${n}`} השבוע, איזה יופי!`, tts: `הָאִמּוּן ${ordTts || `מִסְפָּר ${n}`} הַשָּׁבוּעַ, אֵיזֶה יוֹפִי!` },
    ];
    if (n >= 2) forms.push({ text: `כבר ${n} אימונים השבוע!`, tts: `כְּבָר ${numWordTts(n)} אִמּוּנִים הַשָּׁבוּעַ!` });
    return choose('week', forms);
  };
  const streak = n => choose('streak', [
    { text: `${n} ימים ברצף, וואו!`, tts: `${numWordTts(n)} יָמִים בְּרֶצֶף, וַואוּ!` },
    { text: `כבר ${n} ימים ברצף!`, tts: `כְּבָר ${numWordTts(n)} יָמִים בְּרֶצֶף!` },
    { text: `${n} ימים בלי להפסיק!`, tts: `${numWordTts(n)} יָמִים בְּלִי לְהַפְסִיק!` },
  ]);
  const milestone = n => choose('milestone', [
    { text: `זה האימון מספר ${n}! וואו.`, tts: `זֶה הָאִמּוּן מִסְפָּר ${numWordTts(n)}! וַואוּ.` },
    { text: `${n} אימונים כבר! איזה כוח.`, tts: `${numWordTts(n)} אִמּוּנִים כְּבָר! אֵיזֶה כֹּחַ.` },
  ]);
  // סיכום סוף אימון: חצי משפט שבוע, רצף, אבן דרך, ולפעמים הערה לפי שעה
  const perseverance = (st, ctx = {}) => {
    const parts = [week(st, ctx)];
    if (st.streak >= 2) parts.push(streak(st.streak));
    if (st.workouts === 1) parts.push(pick('firstWorkout', ctx));
    else if ([5, 10, 20, 30, 50, 100].includes(st.workouts)) parts.push(milestone(st.workouts));
    else if (ctx.hour != null && rng() < .35) {
      const dp = dayPart(ctx.hour);
      if (dp === 'morning') parts.push(pick('dayMorning', ctx)); else if (dp === 'evening') parts.push(pick('dayEvening', ctx));
    }
    return { text: parts.map(p => p.text).join(' '), tts: parts.map(p => p.tts).join(' ') };
  };
  return { pick, howWas, perseverance, reset: () => last.clear() };
}

